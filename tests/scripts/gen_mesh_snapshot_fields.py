#!/usr/bin/env python3
"""Regenerate tests/unit/engine/mesh_snapshot_fields.inc.

test_engine_mesh_snapshots dumps every data member of the 2D loader's outputs
(MeshData, SolverOptions2D, the pending rows, the infiltration rows). The member
lists come from clang's AST of the engine headers, so a new member shows up in
the dump (and in a snapshot diff) instead of being skipped silently. Run this
after adding or removing a member of one of those records, then regenerate the
snapshots on purpose (OPENSWMM_UPDATE_MESH_SNAPSHOTS=1) and review the diff.

  gen_mesh_snapshot_fields.py <build-dir-with-compile_commands.json>

Needs a clang++ that understands the build's flags (the one the build used).
"""
import json
import os
import shlex
import subprocess
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(REPO, "tests", "unit", "engine", "mesh_snapshot_fields.inc")
WANTED = [
    "openswmm::FilePathPair",
    "openswmm::twoD::Infil2DDefault", "openswmm::twoD::Infil2DOptions",
    "openswmm::twoD::Infil2DOverride", "openswmm::twoD::Infil2DRow",
    "openswmm::twoD::MeshData", "openswmm::twoD::MeshData::TriCouplingRow",
    "openswmm::twoD::PendingBoundaryQualityRow", "openswmm::twoD::PendingBoundaryRow",
    "openswmm::twoD::PendingEdgeConveyanceRow", "openswmm::twoD::PendingInitialBedQualityRow",
    "openswmm::twoD::PendingInitialQualityRow", "openswmm::twoD::SolverOptions2D",
]
PROBE = '#include "2d/input/SectionHandlers2D.hpp"\n#include "2d/infil/Infil2D.hpp"\n'


def compile_args(build):
    cc = json.load(open(os.path.join(build, "compile_commands.json")))
    e = next(x for x in cc if x["file"].endswith("tests/unit/engine/test_2d_surface_routing.cpp"))
    args = shlex.split(e["command"]) if "command" in e else list(e["arguments"])
    if args[0].endswith("ccache"):
        args = args[1:]
    out, skip = [], False
    for a in args:
        if skip:
            skip = False
            continue
        if a == "-o":
            skip = True
            continue
        if a == "-c" or a.endswith(".o") or a == e["file"]:
            continue
        out.append(a)
    return out, e["directory"]


def objects(text):
    """The concatenated JSON roots -ast-dump-filter prints (with banners between them)."""
    dec = json.JSONDecoder()
    i = 0
    while i < len(text):
        while i < len(text) and text[i] in " \r\n\t":
            i += 1
        if i >= len(text):
            break
        if not text.startswith("{", i):
            i = text.index("\n", i) + 1
            continue
        obj, i = dec.raw_decode(text, i)
        yield obj


def records(node, scope, out):
    """Every complete record under node: qualified-name suffix -> data member names."""
    kind, name = node.get("kind"), node.get("name")
    if kind in ("NamespaceDecl", "CXXRecordDecl") and name:
        full = (scope + "::" if scope else "") + name
        if kind == "CXXRecordDecl" and node.get("completeDefinition"):
            out.setdefault(full, [c["name"] for c in node.get("inner", [])
                                  if c.get("kind") == "FieldDecl"])
        for c in node.get("inner", []):
            records(c, full, out)
    elif kind in (None, "TranslationUnitDecl", "LinkageSpecDecl"):
        for c in node.get("inner", []):
            records(c, scope, out)


def main():
    args, cwd = compile_args(sys.argv[1])
    probe = os.path.join(sys.argv[1], "mesh_snapshot_fields_probe.cpp")
    open(probe, "w").write(PROBE)
    found = {}
    for leaf in sorted({w.split("::")[-1] for w in WANTED}):
        r = subprocess.run([*args, "-fsyntax-only", "-Xclang", "-ast-dump=json", "-Xclang",
                            f"-ast-dump-filter={leaf}", probe],
                           cwd=cwd, capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit(f"clang failed for {leaf}:\n{r.stderr[:2000]}")
        for obj in objects(r.stdout):
            records(obj, "", found)
    os.remove(probe)
    # A filtered dump loses the enclosing scopes: match on the trailing names.
    resolved = {}
    for want in WANTED:
        parts = want.split("::")
        tail = "::".join(parts[-2:]) if want.endswith("::TriCouplingRow") else parts[-1]
        hits = [v for k, v in found.items() if k == tail or k.endswith("::" + tail)]
        if not hits:
            sys.exit(f"record not found: {want}")
        resolved[want] = hits[0]
    lines = ["// Generated by tests/scripts/gen_mesh_snapshot_fields.py -- do not edit by hand.",
             "// Every data member of the records the 2D loader fills, in declaration order.",
             "#ifdef MESH_SNAPSHOT_DECLARATIONS"]
    lines += ["void dump(std::ostream& o, const %s& r);" % w for w in WANTED]
    lines.append("#else")
    for w in WANTED:
        lines.append("void dump(std::ostream& o, const %s& r) {" % w)
        lines.append('    o << "{";')
        for f in resolved[w]:
            lines.append('    o << "%s="; dump(o, r.%s); o << ";";' % (f, f))
        lines.append('    o << "}";')
        lines.append("}")
        lines.append("")
    lines.append("#endif")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print({w.split("::")[-1]: len(resolved[w]) for w in WANTED})


if __name__ == "__main__":
    main()
