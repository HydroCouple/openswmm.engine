"""Synthetic scaling corpus for the model-load benchmark (plan Phase 0.2).

The manufactured benchmarks under ``tests/benchmarks/manufactured/`` are
solver-verification models and are all tiny. Load performance needs big inputs,
so this emits parameterized ``.inp`` files that each stress one suspected
load-path hot spot:

===============  =========================================================
Model            Stresses
===============  =========================================================
grid_N           parse, SoA growth, xsect loop, topology
grid_N_geo       grid_N plus [COORDINATES]/[VERTICES]/[Polygons]
ts_heavy         the find_timeseries/find_curve parse quadratic
gage_heavy       gage binding and the O(G^2) co-gage loop
street_heavy     per-link TransectData duplication, street linear scans
transect_heavy   per-link transect linear scan
inflow_heavy     the dead resolver loop and the report-preamble quadratic
fv_variant       NetworkMeshBuilder per-conduit geometry tabulation
===============  =========================================================

Every model is deterministic: no RNG is used at all, so a given (name, size)
always produces byte-identical output. That matters because the benchmark
compares medians across engine revisions, and it lets the parity gate diff two
engine builds over the same bytes.

Topology is a dendritic binary tree, so it is connected, acyclic and drains to
a single outfall — the shape a real collection network has, and one that keeps
TopoSort and the routing solvers on their normal code paths rather than in
degenerate-graph corners.

Usage::

    python3 gen_load_bench.py --out-dir <dir> [--model NAME ...] [--list]

stdlib only, per the plan.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

# --------------------------------------------------------------------------
# Shared pieces
# --------------------------------------------------------------------------

#: Every model runs a 1-hour window. The benchmark sets END == START so no
#: routing happens; this default only matters when a model is run manually.
_OPTIONS_TMPL = """[TITLE]
{title}
;; Generated by tests/benchmarks/scripts/gen_load_bench.py — do not edit.
;; Deterministic: regenerating with the same arguments reproduces this file.

[OPTIONS]
FLOW_UNITS           CFS
INFILTRATION         HORTON
FLOW_ROUTING         {routing}
LINK_OFFSETS         DEPTH
MIN_SLOPE            0
START_DATE           01/01/2020
START_TIME           00:00:00
END_DATE             01/01/2020
END_TIME             01:00:00
REPORT_STEP          00:05:00
WET_STEP              00:05:00
DRY_STEP             01:00:00
ROUTING_STEP         5
"""


def _tree_parent(i: int) -> int:
    """Parent of node ``i`` in a 0-rooted binary tree."""
    return (i - 1) // 2


def _grid_body(n: int, *, geometry: bool) -> list[str]:
    """Junctions + one outfall + conduits over a dendritic binary tree.

    Node 0 is the root and drains to the single outfall; node ``i>0`` drains to
    its tree parent. Inverts decrease with depth so every conduit has positive
    slope and the model produces no MIN_SLOPE or adverse-slope warnings — the
    benchmark measures load work, not warning formatting (that is what item 3.7
    and its own model are for).
    """
    out: list[str] = []

    out.append("\n[JUNCTIONS]")
    out.append(";;Name  Elev  MaxDepth  InitDepth  SurDepth  Aponded")
    for i in range(n):
        depth = i.bit_length()  # tree depth of node i, 0 for the root
        elev = 100.0 + depth * 0.5
        out.append(f"J{i}  {elev:.2f}  8  0  0  0")

    out.append("\n[OUTFALLS]")
    out.append(";;Name  Elev  Type  Stage  Gated")
    out.append("OUT0  95.00  FREE         NO")

    out.append("\n[CONDUITS]")
    out.append(";;Name  From  To  Length  Rough  In  Out  Init  Max")
    out.append("C0  J0  OUT0  400  0.013  0  0  0  0")
    for i in range(1, n):
        out.append(f"C{i}  J{i}  J{_tree_parent(i)}  400  0.013  0  0  0  0")

    out.append("\n[XSECTIONS]")
    out.append(";;Link  Shape  Geom1  Geom2  Geom3  Geom4  Barrels")
    # Cycle a few shapes so the xsect parameter loop and its shape-group
    # batching see a realistic mix rather than one homogeneous group.
    shapes = [
        ("CIRCULAR", "1.5  0  0  0"),
        ("RECT_CLOSED", "2.0  3.0  0  0"),
        ("TRAPEZOIDAL", "2.5  4.0  1.0  1.0"),
        ("CIRCULAR", "2.0  0  0  0"),
    ]
    for i in range(n):
        name, geom = shapes[i % len(shapes)]
        out.append(f"C{i}  {name}  {geom}  1")

    if geometry:
        # Row-count leaders in real models: coordinates for every node, three
        # interior vertices per link, and a 6-point polygon per subcatchment.
        out.append("\n[COORDINATES]")
        out.append(";;Node  X  Y")
        for i in range(n):
            out.append(f"J{i}  {i * 10.0:.1f}  {(i % 97) * 10.0:.1f}")
        out.append(f"OUT0  {n * 10.0:.1f}  0.0")

        out.append("\n[VERTICES]")
        out.append(";;Link  X  Y")
        for i in range(n):
            x0 = i * 10.0
            y0 = (i % 97) * 10.0
            for v in range(1, 4):
                out.append(f"C{i}  {x0 + v * 2.5:.1f}  {y0 + v * 1.5:.1f}")

        n_sub = max(1, n // 4)
        out.append("\n[SUBCATCHMENTS]")
        out.append(";;Name  Gage  Outlet  Area  %Imperv  Width  Slope  CurbLen")
        out.append("\n[RAINGAGES]")
        out.append(";;Name  Format  Interval  SCF  Source")
        out.append("RG0  INTENSITY  1:00  1.0  TIMESERIES  TS0")
        out.append("\n[TIMESERIES]")
        out.append(";;Name  Date  Time  Value")
        for h in range(4):
            out.append(f"TS0  01/01/2020  {h:02d}:00  {0.1 * h:.2f}")
        # Emitted after the gage/series they reference so the file is readable;
        # the parser is order-independent either way.
        subs = ["\n[SUBCATCHMENTS]", ";;Name  Gage  Outlet  Area  %Imperv  Width  Slope  CurbLen"]
        for s in range(n_sub):
            subs.append(f"S{s}  RG0  J{s % n}  2.5  50  500  0.5  0")
        subs.append("\n[SUBAREAS]")
        subs.append(";;Subcatch  N-Imperv  N-Perv  S-Imperv  S-Perv  PctZero  RouteTo")
        for s in range(n_sub):
            subs.append(f"S{s}  0.01  0.1  0.05  0.05  25  OUTLET")
        subs.append("\n[INFILTRATION]")
        subs.append(";;Subcatch  MaxRate  MinRate  Decay  DryTime  MaxInfil")
        for s in range(n_sub):
            subs.append(f"S{s}  3.0  0.5  4  7  0")
        subs.append("\n[Polygons]")
        subs.append(";;Subcatch  X  Y")
        for s in range(n_sub):
            cx = s * 40.0
            cy = (s % 53) * 40.0
            for k, (dx, dy) in enumerate(
                [(0, 0), (20, 0), (30, 15), (20, 30), (0, 30), (-10, 15)]
            ):
                subs.append(f"S{s}  {cx + dx:.1f}  {cy + dy:.1f}")
        # Drop the two empty placeholder headers written above.
        out = [ln for ln in out if ln not in ("\n[SUBCATCHMENTS]",
                                              ";;Name  Gage  Outlet  Area  %Imperv  Width  Slope  CurbLen")]
        out.extend(subs)

    return out


