def _reach_inp(n_conduits: int, graded: bool) -> str:
    """A single chain of ``n_conduits`` pipes, one inflow at the head.

    ``graded`` varies the pipe diameter and slope down the chain, which is what
    made the "graded" column of Chapter 8 §8.10 stiffer for the implicit solver
    (its own step collapses) and unchanged for the explicit one. Uniform holds
    both constant. Deterministic: no RNG, so two people generate byte-identical
    decks.
    """
    lines: list[str] = []
    lines.append("[TITLE]")
    kind = "graded" if graded else "uniform"
    lines.append(f";; Synthetic {kind} reach, {n_conduits} conduits.")
    lines.append(";; Generated by tests/benchmarks/scripts/fv_perf_baseline.py")
    lines.append(";; Deterministic — regenerate rather than commit.")
    lines.append("")
    lines.append("[OPTIONS]")
    lines.append("FLOW_UNITS           CFS")
    lines.append("INFILTRATION         HORTON")
    lines.append("FLOW_ROUTING         DYNWAVE")
    lines.append("LINK_OFFSETS         DEPTH")
    lines.append("MIN_SLOPE            0")
    lines.append("ALLOW_PONDING        NO")
    lines.append("SKIP_STEADY_STATE    NO")
    lines.append("START_DATE           01/01/2026")
    lines.append("START_TIME           00:00:00")
    lines.append("REPORT_START_DATE    01/01/2026")
    lines.append("REPORT_START_TIME    00:00:00")
    lines.append("END_DATE             01/01/2026")
    lines.append("END_TIME             02:00:00")
    lines.append("SWEEP_START          01/01")
    lines.append("SWEEP_END            12/31")
    lines.append("DRY_DAYS             0")
    lines.append("REPORT_STEP          00:05:00")
    lines.append("WET_STEP             00:05:00")
    lines.append("DRY_STEP             01:00:00")
    lines.append("ROUTING_STEP         0:00:05")
    lines.append("INERTIAL_DAMPING     PARTIAL")
    lines.append("NORMAL_FLOW_LIMITED  BOTH")
    lines.append("FORCE_MAIN_EQUATION  H-W")
    lines.append("VARIABLE_STEP        0.75")
    lines.append("LENGTHENING_STEP     0")
    lines.append("MIN_SURFAREA         12.566")
    lines.append("MAX_TRIALS           8")
    lines.append("HEAD_TOLERANCE       0.005")
    lines.append("SYS_FLOW_TOL         5")
    lines.append("LAT_FLOW_TOL         5")
    lines.append("")

    n_nodes = n_conduits + 1
    # Bed: uniform 0.1 % throughout, or graded from 2 % at the head to 0.05 %
    # at the outfall. Elevations are accumulated so the profile is monotone by
    # construction and no invert collides with the one below it.
    z = [0.0] * n_nodes
    elev = 100.0
    for i in range(n_nodes):
        z[i] = elev
        if graded:
            # Clamped: the node loop runs one past the last conduit, and an
            # unclamped frac > 1 would extrapolate the slope toward zero and
            # eventually negative — an adverse bed nobody asked for.
            frac = min(1.0, i / max(1, n_conduits - 1))
            slope = 0.02 * (1.0 - frac) + 0.0005 * frac
        else:
            slope = 0.001
        elev -= slope * 400.0

    lines.append("[JUNCTIONS]")
    lines.append(";;Name  Elev   MaxDepth  InitDepth  SurDepth  Aponded")
    for i in range(n_nodes - 1):
        lines.append(f"J{i:05d}  {z[i]:.4f}  12  0  0  0")
    lines.append("")
    lines.append("[OUTFALLS]")
    lines.append(";;Name  Elev   Type   Stage  Gated")
    lines.append(f"OUT     {z[-1]:.4f}  FREE   ,      NO")
    lines.append("")

    lines.append("[CONDUITS]")
    lines.append(";;Name  From  To  Length  N  InOff  OutOff  InitFlow  MaxFlow")
    for i in range(n_conduits):
        frm = f"J{i:05d}"
        to = f"J{i + 1:05d}" if i + 1 < n_nodes - 1 else "OUT"
        lines.append(f"C{i:05d}  {frm}  {to}  400  0.013  0  0  0  0")
    lines.append("")

    lines.append("[XSECTIONS]")
    lines.append(";;Link  Shape     Geom1  Geom2  Geom3  Geom4  Barrels")
    for i in range(n_conduits):
        if graded:
            # Diameter widens downstream: 2.0 ft at the head to 6.0 ft at the
            # outfall. Combined with the flattening bed this is the classic
            # stiff grading — short celerity-limited cells upstream, long ones
            # downstream, which is what LTS exists for.
            frac = i / max(1, n_conduits - 1)
            d = 2.0 + 4.0 * frac
        else:
            d = 4.0
        lines.append(f"C{i:05d}  CIRCULAR  {d:.3f}  0  0  0  1")
    lines.append("")

    lines.append("[INFLOWS]")
    lines.append(";;Node  Constituent  TimeSeries  Type  Mfactor  Sfactor  Base  Pattern")
    lines.append("J00000  FLOW  INFLOW  FLOW  1.0  1.0")
    lines.append("")
    lines.append("[TIMESERIES]")
    lines.append(";;Name  Date  Time  Value")
    lines.append("INFLOW  0:00   0")
    lines.append("INFLOW  0:15  30")
    lines.append("INFLOW  0:45  30")
    lines.append("INFLOW  1:00   0")
    lines.append("INFLOW  2:00   0")
    lines.append("")
    lines.append("[REPORT]")
    lines.append("INPUT      NO")
    lines.append("CONTROLS   NO")
    lines.append("SUBCATCHMENTS  NONE")
    lines.append("NODES      NONE")
    lines.append("LINKS      NONE")
    lines.append("")
    return "\n".join(lines) + "\n"


def generate_synthetics(dest: Path) -> list[Path]:
    """Writes the six reach decks and returns their paths."""
    dest.mkdir(parents=True, exist_ok=True)
    out = []
    for n in (50, 500, 2000):
        for graded in (False, True):
            kind = "graded" if graded else "uniform"
            p = dest / f"reach_{kind}_{n}.inp"
            p.write_text(_reach_inp(n, graded), encoding="utf-8")
            out.append(p)
    return out


