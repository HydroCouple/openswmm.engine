"""FV 1D solver performance baseline driver.

Phase 0 of ``plans/FV1D_PERF_PLAN_REVISED_2026-08-20.md``. Produces the
document every later commit in the FV optimization program is measured
against, and the ``.out`` hashes that make the Tier A ("bit-identical")
acceptance gate mechanical rather than a judgement call.

What it records per (deck, configuration):

* **wall clock**, best-of-N, so a scheduler hiccup does not become a finding;
* **the ``[PERF-FV]`` phase split** from the engine's own timers, which is what
  re-ranks the optimization phases against a profile instead of a recollection;
* **routing continuity error** parsed from the ``.rpt`` — a speedup that moves
  continuity is not a speedup;
* **a SHA-256 of the ``.out``**, so "bit-identical" is checked, not asserted.

Why the synthetic reaches are GENERATED here rather than committed: the
50/500/2000-conduit uniform and graded reaches behind the Chapter 8 §8.10
scaling table were built ad hoc and never checked in, which is exactly why that
table cannot be reproduced today. Generating them from a seed-free
deterministic rule makes the row reproducible by anyone with this script.

Usage::

    python3 fv_perf_baseline.py --engine build/darwin/src/cli/openswmm \\
        [--label baseline] [--repeat 3] [--outdir DIR] [--only PATTERN]

stdlib only. Writes everything under ``--outdir`` (default
``tests/benchmarks/generated/fv_perf/<label>_<date>/``) so every input and
output of a benchmark run is on disk for review, per CLAUDE.md §4.1.
"""

