def markdown(results: list[dict], meta: dict) -> str:
    L: list[str] = []
    L.append("# FV 1D Solver Performance Baseline")
    L.append("")
    L.append(f"**Label:** `{meta['label']}`  ")
    L.append(f"**Date:** {meta['date']}  ")
    L.append(f"**Commit:** `{meta['commit']}`  ")
    L.append(f"**Host:** {meta['host']}  ")
    L.append(f"**Engine:** `{meta['engine']}`  ")
    L.append(f"**Repeats:** {meta['repeat']} (best-of reported)")
    L.append("")
    L.append("Generated by `tests/benchmarks/scripts/fv_perf_baseline.py`. "
             "Every deck actually run is written next to this file, so a row "
             "can be reproduced without reconstructing its options.")
    L.append("")

    # ---- headline table -------------------------------------------------
    L.append("## 1. Wall clock and ratio to dynamic wave")
    L.append("")
    L.append("| deck | config | wall (s) | x DW | substeps/step | continuity % | deterministic |")
    L.append("|---|---|---:|---:|---:|---:|:-:|")
    by_deck: dict[str, dict[str, dict]] = {}
    for r in results:
        by_deck.setdefault(r["deck"], {})[r["config"]] = r
    for deck, configs in by_deck.items():
        dw = configs.get("dynwave")
        dw_wall = dw["wall_best"] if dw and dw["ok"] else None
        for cfg, r in configs.items():
            if not r["ok"]:
                L.append(f"| {deck} | {cfg} | — | — | — | — | — |  <!-- {r['reason']} -->")
                continue
            ratio = (f"{r['wall_best'] / dw_wall:.1f}"
                     if dw_wall and dw_wall > 0 and cfg != "dynwave" else "1.0")
            sub = (f"{r['substeps_per_step']:.2f}"
                   if r["substeps_per_step"] is not None else "—")
            cont = (f"{r['continuity_pct']:.3f}"
                    if r["continuity_pct"] is not None else "—")
            det = "yes" if r["deterministic"] else "**NO**"
            L.append(f"| {deck} | {cfg} | {r['wall_best']:.2f} | {ratio} | "
                     f"{sub} | {cont} | {det} |")
    L.append("")

    # ---- phase split ----------------------------------------------------
    L.append("## 2. FV phase split (`[PERF-FV]`, best run of each FV config)")
    L.append("")
    L.append("Percentages are of `total` — the sum of the bracketed phases. "
             "`unattributed` is `step - total`: routing-step time the FV timers "
             "did not claim. A large unattributed share means a phase is "
             "missing from the instrumentation, and is itself the finding.")
    L.append("")
    header = "| deck | config | step (s) | total (s) | unattr % | " + \
             " | ".join(short for _, short in PHASES) + " |"
    L.append(header)
    L.append("|---|---|---:|---:|---:|" + "---:|" * len(PHASES))
    for r in results:
        p = r.get("perf") or {}
        if not p or r["config"] == "dynwave":
            continue
        step, total = p.get("step", 0.0), p.get("total", 0.0)
        unattr = (100.0 * (step - total) / step) if step > 0 else 0.0
        cells = []
        for key, _ in PHASES:
            v = p.get(key, 0.0)
            cells.append(f"{100.0 * v / total:.1f}" if total > 0 else "—")
        L.append(f"| {r['deck']} | {r['config']} | {step:.2f} | {total:.2f} | "
                 f"{unattr:.1f} | " + " | ".join(cells) + " |")
    L.append("")

    # ---- counters -------------------------------------------------------
    L.append("## 3. Work counters")
    L.append("")
    L.append("`algflux_per_solve` is the face-flux multiplier the algebraic "
             "node solve pays (Phase 3a targets it). `rollback_frac` is how "
             "often the per-substep `saveState` snapshot is actually used "
             "(Phase 1b argues it is rare). `passthru_frac` is the degree-2 "
             "shortcut share (Phase 3c targets it).")
    L.append("")
    L.append("| deck | config | substeps | censuses | inversions | alg solves | "
             "resid/solve | flux/solve | passthru frac | rollback frac |")
    L.append("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for r in results:
        p = r.get("perf") or {}
        if not p or r["config"] == "dynwave":
            continue
        g = lambda k: p.get(k, 0.0)  # noqa: E731
        L.append(
            f"| {r['deck']} | {r['config']} | {int(g('n.substep'))} | "
            f"{int(g('n.census'))} | {int(g('n.invert'))} | "
            f"{int(g('n.algsolve'))} | {g('algresid_per_solve'):.2f} | "
            f"{g('algflux_per_solve'):.2f} | {g('passthru_frac'):.3f} | "
            f"{g('rollback_frac'):.4f} |")
    L.append("")

    # ---- hashes ---------------------------------------------------------
    L.append("## 4. Result hashes (Tier A gate)")
    L.append("")
    L.append("A Tier A change must reproduce every hash below. A change that "
             "does not is Tier B or C and needs the corresponding gate, "
             "whatever its author intended.")
    L.append("")
    L.append("| deck | config | sha256(.out) |")
    L.append("|---|---|---|")
    for r in results:
        if r["ok"] and r["out_sha256"]:
            L.append(f"| {r['deck']} | {r['config']} | `{r['out_sha256'][:32]}…` |")
    L.append("")

    failed = [r for r in results if not r["ok"]]
    if failed:
        L.append("## 5. Failures")
        L.append("")
        for r in failed:
            L.append(f"* **{r['deck']} / {r['config']}** — {r['reason']}")
            if r.get("stderr_tail"):
                L.append("")
                L.append("  ```")
                for line in r["stderr_tail"].splitlines()[-12:]:
                    L.append(f"  {line}")
                L.append("  ```")
        L.append("")
    return "\n".join(L) + "\n"


