#: `key=value` pairs on the engine's [PERF-FV] stderr line.
_PERF_RE = re.compile(r"([A-Za-z0-9_.]+)=([-0-9.eE]+)")

#: "  Flow Routing Continuity ...  ... Continuity Error (%) .....   0.000"
_CONTINUITY_RE = re.compile(
    r"Flow Routing Continuity.*?Continuity Error \(%\)\s*\.*\s*(-?[0-9.]+)",
    re.DOTALL,
)

_SUBSTEPS_RE = re.compile(r"Average Substeps per Step\s*:\s*([0-9.]+)")
_EXPLICIT_SUBSTEPS_RE = re.compile(r"Explicit Substeps\s*\.*\s*([0-9]+)")

