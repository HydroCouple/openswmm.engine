def write_variant(src: Path, dest: Path, overrides: dict[str, str]) -> None:
    """Copies ``src`` to ``dest`` with ``[OPTIONS]`` keys forced to ``overrides``.

    Keys already present are replaced in place; keys absent are appended to the
    ``[OPTIONS]`` section. Deliberately textual — round-tripping through the
    engine's own writer would fold in normalizations that make a deck diff
    unreadable, and this file is meant to be reviewed.
    """
    text = src.read_text(encoding="utf-8", errors="replace")
    lines = text.splitlines()
    remaining = dict(overrides)
    out: list[str] = []
    in_options = False
    options_end = -1

    for line in lines:
        stripped = line.strip()
        if stripped.startswith("["):
            if in_options:
                options_end = len(out)
                in_options = False
            if stripped.upper().startswith("[OPTIONS]"):
                in_options = True
            out.append(line)
            continue
        if in_options and stripped and not stripped.startswith(";"):
            key = stripped.split()[0].upper()
            if key in remaining:
                out.append(f"{key}  {remaining.pop(key)}")
                continue
        out.append(line)

    if in_options:
        options_end = len(out)
    if remaining:
        extra = [f"{k}  {v}" for k, v in remaining.items()]
        if options_end < 0:
            out = ["[OPTIONS]"] + extra + [""] + out
        else:
            out[options_end:options_end] = extra

    dest.write_text("\n".join(out) + "\n", encoding="utf-8")


