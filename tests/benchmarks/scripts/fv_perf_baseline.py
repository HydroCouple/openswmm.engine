    ("census", "census"), ("flux", "flux"), ("nodesolve", "nodesolve"),
    ("positivity", "positivity"), ("cellupdate", "cellupdate"),
    ("nodeupdate", "nodeupdate"), ("refreshdepths", "refreshdep"),
